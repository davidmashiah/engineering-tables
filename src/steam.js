// region 2 (vapour) and region 4 (saturation line), which together cover the
// saturation tables from the triple point to 350 °C. Units: T in K, p in MPa,
// v in m³/kg, h in kJ/kg, s in kJ/(kg·K). test/steam.test.mjs checks every
// function against the verification values published in the standard.

