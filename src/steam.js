function inRange(name, x, lo, hi, unit) {
  if (!(x >= lo && x <= hi)) throw new RangeError(`${name} must be between ${lo} and ${hi} ${unit}, got ${x}`)
}

/** Region 1 (liquid) properties at T (K, 273.15 to 623.15), p (MPa, up to 100). */
export function region1(T, p) {
  inRange("T", T, 273.15, 623.15, "K"); inRange("p", p, 0, 100, "MPa")
  const pi = p / 16.53, tau = 1386 / T
  let g = 0, gp = 0, gt = 0
  for (const [I, J, n] of R1) {
    const a = 7.1 - pi, b = tau - 1.222
    g += n * a ** I * b ** J
    gp += -n * I * a ** (I - 1) * b ** J
    gt += n * a ** I * J * b ** (J - 1)
  }
  return { v: (R * T / p) * pi * gp / 1000, h: R * T * tau * gt, s: R * (tau * gt - g) }
}

