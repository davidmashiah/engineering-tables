/** Region 2 (vapour) properties at T (K, 273.15 to 1073.15), p (MPa, above 0, up to 100). */
export function region2(T, p) {
  inRange("T", T, 273.15, 1073.15, "K"); if (!(p > 0)) throw new RangeError(`p must be above 0 MPa, got ${p}`); inRange("p", p, 0, 100, "MPa")
  const pi = p, tau = 540 / T
  let g0 = Math.log(pi), g0t = 0
  for (const [J, n] of R2o) { g0 += n * tau ** J; g0t += n * J * tau ** (J - 1) }
  let gr = 0, grp = 0, grt = 0
  for (const [I, J, n] of R2r) {
    const b = tau - 0.5
    gr += n * pi ** I * b ** J
    grp += n * I * pi ** (I - 1) * b ** J
    grt += n * pi ** I * J * b ** (J - 1)
  }
  const gp = 1 / pi + grp
  return { v: (R * T / p) * pi * gp / 1000, h: R * T * tau * (g0t + grt), s: R * (tau * (g0t + grt) - (g0 + gr)) }
}

// Region 4: saturation line.
const N = [0, 0.11670521452767e4, -0.72421316703206e6, -0.17073846940092e2, 0.1202082470247e5, -0.32325550322333e7,
  0.1491510861353e2, -0.48232657361591e4, 0.40511340542057e6, -0.23855557567849, 0.65017534844798e3]

/** Saturation pressure (MPa) at T (K), 273.15 to 647.096 K. */
export function psat(T) {
  inRange("T", T, 273.15, 647.096, "K")
  const th = T + N[9] / (T - N[10])
  const A = th * th + N[1] * th + N[2], B = N[3] * th * th + N[4] * th + N[5], C = N[6] * th * th + N[7] * th + N[8]
  return (2 * C / (-B + Math.sqrt(B * B - 4 * A * C))) ** 4
}

/** Saturation temperature (K) at p (MPa), 611.213 Pa to 22.064 MPa. */
export function tsat(p) {
  inRange("p", p, 0.000611213, 22.064, "MPa")
  const b = p ** 0.25
  const E = b * b + N[3] * b + N[6], F = N[1] * b * b + N[4] * b + N[7], G = N[2] * b * b + N[5] * b + N[8]
  const D = 2 * G / (-F - Math.sqrt(F * F - 4 * E * G))
  return (N[10] + D - Math.sqrt((N[10] + D) ** 2 - 4 * (N[9] + N[10] * D))) / 2
}

/** Saturated liquid (f) and vapour (g) properties at T (K), up to 623.15 K. */
export function saturated(T) {
  inRange("T", T, 273.15, 623.15, "K")
  const p = psat(T), f = region1(T, p), g = region2(T, p)
  return { T, p, vf: f.v, vg: g.v, hf: f.h, hg: g.h, hfg: g.h - f.h, sf: f.s, sg: g.s, sfg: g.s - f.s }
}
